#!/usr/bin/env python3
"""Generate 1-bit bitmap fonts for the watch face from DejaVu (Bitstream Vera licence).

Usage: python3 firmware/tools/gen_font.py > firmware/src/fonts.c
Needs Pillow and the DejaVu fonts (fonts-dejavu-core).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"

FONTS = [
    # name, ttf, pixel size, characters
    ("font_big", "DejaVuSans-Bold.ttf", 32, "0123456789:-"),
    ("font_small", "DejaVuSans-Bold.ttf", 11, " 0123456789:+-.%/ABCDEFGHIJKLMNOPQRSTUVWXYZ"),
]


def glyph(font, ch, asc, height):
    l, t, r, b = font.getbbox(ch)
    adv = int(round(font.getlength(ch)))
    w = max(adv, 1)
    img = Image.new("1", (w, height), 0)
    ImageDraw.Draw(img).text((0, asc - font.getmetrics()[0]), ch, font=font, fill=1)
    # trim empty columns either side but keep 1 px spacing
    cols = [x for x in range(w) if any(img.getpixel((x, y)) for y in range(height))]
    if cols:
        x0, x1 = cols[0], cols[-1] + 1
        img = img.crop((x0, 0, x1, height))
        w = x1 - x0
    else:
        w = max(adv // 2, 3)
        img = Image.new("1", (w, height), 0)
    return img, w


def emit(name, ttf, size, chars, out):
    font = ImageFont.truetype(DEJAVU + ttf, size)
    # common height: tallest ink of the set
    tops, bots = [], []
    for ch in chars:
        if ch.strip():
            l, t, r, b = font.getbbox(ch)
            tops.append(t)
            bots.append(b)
    top, bot = min(tops), max(bots)
    height = bot - top
    asc = font.getmetrics()[0] - top
    glyphs = [glyph(font, ch, asc, height) for ch in chars]
    stride = lambda w: (w + 7) // 8
    data, offs = [], []
    for img, w in glyphs:
        offs.append(len(data))
        for y in range(height):
            row = 0
            for x in range(w):
                if img.getpixel((x, y)):
                    row |= 1 << x
            for i in range(stride(w)):
                data.append((row >> (8 * i)) & 0xFF)
    out.write(f"/* {ttf} at {size} px: \"{chars}\" */\n")
    out.write(f"static const uint8_t {name}_bits[{len(data)}] = {{\n")
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",\n")
    out.write("};\n")
    out.write(f"static const font_glyph_t {name}_glyphs[{len(chars)}] = {{\n")
    for ch, (img, w), off in zip(chars, glyphs, offs):
        esc = ch.replace("\\", "\\\\").replace("'", "\\'")
        out.write(f"    {{'{esc}', {w}, {off}}},\n")
    out.write("};\n")
    out.write(f"const font_t {name} = {{{height}, {len(chars)}, {name}_glyphs, {name}_bits}};\n\n")


def main():
    out = sys.stdout
    out.write("/* Generated by firmware/tools/gen_font.py. Do not edit. */\n")
    out.write("/* Glyphs from DejaVu fonts (Bitstream Vera licence). */\n")
    out.write('#include "gfx.h"\n\n')
    for f in FONTS:
        emit(*f, out)


if __name__ == "__main__":
    main()
